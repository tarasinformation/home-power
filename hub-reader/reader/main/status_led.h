// Індикація стану кольоровим світлодіодом плати (WS2812 на GPIO8 в ESP32-C6 Super Mini).
//
// Правило: поки все працює, світлодіод вимкнений. Світло означає, що щось відбувається або не так:
//   запуск, до першого вдалого звіту   білий, повільно мигає (не довше півтори хвилини)
//   оновлення прошивки по Wi-Fi        блакитний, світить
//   немає Wi-Fi                        жовтий спалах раз на 10 с
//   немає показів із хаба              синій спалах раз на 10 с
//   сайт не приймає звіти              червоний спалах раз на 10 с
//   вдома немає світла                 фіолетовий спалах раз на 10 с
// Якщо причин кілька, спалахи йдуть один за одним.
//
// Зелений світлодіод цієї плати — індикатор зарядки акумулятора: до процесора він не під'єднаний,
// мигає, коли акумулятора немає, і прошивкою не керується.
#pragma once

#include <stdint.h>

#define LED_NO_WIFI 1u
#define LED_NO_HUB 2u
#define LED_NO_SERVER 4u
#define LED_NO_POWER 8u

/** Готує світлодіод і запускає задачу індикації. Якщо драйвер не запустився, плата працює без індикації. */
void status_led_start(void);

/** Поточний набір причин (LED_NO_*), 0 — усе гаразд. Викликати можна як завгодно часто. */
void status_led_set(uint32_t issues);

/** Перший вдалий звіт на сайт: кінець «запуску». */
void status_led_booted(void);

/** Щось змінилося поза набором причин (почалось або скасувалось оновлення): перечитати стан. */
void status_led_refresh(void);

/** Показати всі кольори по секунді (GET /led): перевірити світлодіод і згадати, що який колір значить. */
void status_led_demo(void);
